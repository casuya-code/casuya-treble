VENUES: dict[str, tuple[float, float]] = {}
for _name, _lat, _lon in _GROUNDS:
    _key = team_key(_name)
    _point = (_lat, _lon)
    if _key in VENUES and VENUES[_key] != _point:
        raise RuntimeError(f"two clubs share the weather key {_key}")
    VENUES[_key] = _point


def venue_for(team: str) -> tuple[float, float] | None:
    """Home ground for a club, or None when we do not know the stadium."""
    return VENUES.get(team_key(team))
